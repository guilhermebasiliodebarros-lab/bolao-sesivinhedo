async function databaseNetwork(page, enabled) {
  await page.evaluate(async ({ project, enabled }) => {
    const source = await (await fetch('/src/services/firebase.js')).text()
    const modulePath = source.match(/from ["']([^"']*firebase_firestore[^"']*)["']/)?.[1]
    if (!modulePath?.startsWith('/node_modules/')) throw new Error('SDK local não encontrado.')
    const { db } = await import('/src/services/firebase.js')
    if (db.app.options.projectId !== project) throw new Error('Somente o banco fictício pode ser testado.')
    const sdk = await import(modulePath)
    await (enabled ? sdk.enableNetwork(db) : sdk.disableNetwork(db))
  }, { project: PROJECT, enabled })
}
