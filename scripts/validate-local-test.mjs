import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import { chromium } from 'playwright'
import { APP_ORIGIN, FIRESTORE_ORIGIN, PROJECT, REHEARSAL_PASSWORD, localRequest, resetRehearsal } from './rehearsal-data.mjs'

const output = 'artifacts/rehearsal'
mkdirSync(output, { recursive: true })
const results = [], errors = [], writes = []
const record = (name) => { results.push(name); console.log(`OK · ${name}`) }
const base = `${FIRESTORE_ORIGIN}/v1/projects/${PROJECT}/databases/(default)/documents`
const readGames = async () => ((await localRequest(`${base}/games?pageSize=1000`)).documents || []).sort((a, b) => a.name.localeCompare(b.name))
let browser, page, active = false
try {
  await resetRehearsal()
  browser = await chromium.launch({ channel: process.platform === 'win32' ? 'msedge' : undefined, headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  await context.route('**/*', (route) => {
    const url = new URL(route.request().url())
    if (['localhost', '127.0.0.1', '[::1]'].includes(url.hostname) || !['http:', 'https:'].includes(url.protocol)) return route.continue()
    return route.abort()
  })
  context.on('request', (request) => {
    const url = new URL(request.url())
    if (active && url.port === '8180' && (/\/Write\//.test(url.pathname) || /:commit|:batchWrite/.test(url.pathname))) writes.push(url.pathname)
  })
  context.on('page', (value) => value.on('pageerror', (error) => errors.push(error.message)))
  page = await context.newPage()
  await page.goto(`${APP_ORIGIN}/#login`)
  await page.locator('input[autocomplete="username"]').fill('suporte')
  await page.locator('input[autocomplete="current-password"]').fill(REHEARSAL_PASSWORD)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  const nav = page.getByRole('navigation', { name: 'Seções do painel master' })
  await nav.waitFor()
  await page.getByText('Preparando as turmas de todos os esportes…', { exact: true }).waitFor({ state: 'detached' })
  await nav.getByRole('button', { name: /^Ensaio geral/ }).click()
  assert.equal(await page.locator('a[href*="5179"]').count(), 0)
  const before = await readGames()
  const selectionBefore = await localRequest(`${base}/broadcastSettings/scoreboard`)
  const officialTV = await context.newPage()
  await officialTV.goto(`${APP_ORIGIN}/#placar`)
  await officialTV.getByRole('heading', { name: 'Aguardando os jogos.', exact: true }).waitFor()
  await page.bringToFront()
  active = true
  await page.getByRole('button', { name: 'Iniciar modo de teste', exact: true }).click()
  const testMode = page.getByRole('region', { name: 'Modo de teste dentro do sistema' })
  const operation = testMode.locator('.local-test-operation')
  const preview = testMode.getByRole('region', { name: 'TV de teste', exact: true })
  await operation.getByRole('button', { name: 'Adiantar 1 minuto neste jogo', exact: true }).click()
  await operation.getByRole('button', { name: 'Gol de Ana Beatriz de Teste · equipe A', exact: true }).click()
  await preview.locator('.sb-incidents').getByText('Ana', { exact: true }).waitFor()
  assert.match(await preview.locator('.sb-incidents').innerText(), /1′/)
  assert.equal(await preview.locator('.sb-score').first().innerText(), '1')
  record('Modo dentro do sistema: gol com bola, aluno e minuto na mesma apresentação da TV')
  const cards = operation.getByRole('region', { name: 'Cartões da partida', exact: true })
  await cards.getByRole('combobox', { name: 'Aluno do cartão', exact: true }).selectOption('teste-futebol-1-a-aluno-1')
  await cards.getByRole('button', { name: 'Revisar cartão', exact: true }).click()
  await cards.getByRole('button', { name: 'Confirmar cartão', exact: true }).click()
  await preview.locator('.sb-incidents li .is-yellow').waitFor()
  await cards.getByRole('button', { name: 'Anular cartão', exact: true }).click()
  await cards.getByRole('textbox', { name: 'Motivo da anulação', exact: true }).fill('Corrigir cartão fictício.')
  await cards.getByRole('button', { name: 'Confirmar anulação do cartão', exact: true }).click()
  await preview.locator('.sb-incidents li .is-yellow').waitFor({ state: 'detached' })
  record('Cartão lançado e anulado somente na sessão de teste')
  await preview.getByRole('button', { name: 'Ampliar TV de teste', exact: true }).click()
  const tvDialog = page.getByRole('dialog', { name: 'TV de teste ampliada', exact: true })
  await tvDialog.getByRole('button', { name: 'Tela cheia', exact: true }).click()
  await page.waitForFunction(() => Boolean(document.fullscreenElement))
  assert.match(await tvDialog.innerText(), /MODO TESTE/)
  await page.screenshot({ path: `${output}/local-test-tv.png` })
  await tvDialog.getByRole('button', { name: 'Voltar aos controles', exact: true }).click()
  await tvDialog.waitFor({ state: 'detached' })
  assert.equal(await page.evaluate(() => Boolean(document.fullscreenElement)), false)
  record('TV de teste ampliada e em tela cheia, com retorno aos controles')
  await context.setOffline(true)
  await operation.getByRole('button', { name: 'Gol de Ana Beatriz de Teste · equipe A', exact: true }).click()
  await preview.locator('.sb-score').first().getByText('2', { exact: true }).waitFor()
  await context.setOffline(false)
  record('Os comandos da simulação continuam locais mesmo sem internet')
  const sports = testMode.getByRole('navigation', { name: 'Esporte do teste' })
  await sports.getByRole('button', { name: 'Basquete · 2 jogos', exact: true }).click()
  await operation.getByRole('button', { name: '+3 pontos', exact: true }).click()
  await operation.getByRole('button', { name: 'Ponto de Ana Beatriz de Teste · equipe A', exact: true }).click()
  assert.equal(await preview.locator('.sb-match').count(), 2)
  await preview.locator('[data-game-id="teste-basquete-1"] .sb-score').first().getByText('3', { exact: true }).waitFor()
  await operation.getByRole('combobox', { name: 'Jogo para operar', exact: true }).selectOption('teste-basquete-2')
  await operation.getByRole('button', { name: '+1 ponto', exact: true }).click()
  await operation.getByRole('button', { name: 'Ponto de Carla Maria de Teste · equipe B', exact: true }).click()
  await preview.locator('[data-game-id="teste-basquete-2"] .sb-score').last().getByText('1', { exact: true }).waitFor()
  record('Basquete de teste: dois jogos independentes com cestas de 3 e 1')
  await page.screenshot({ path: `${output}/local-test-basketball.png`, fullPage: true })
  await sports.getByRole('button', { name: 'Vôlei · 2 jogos', exact: true }).click()
  for (let i = 0; i < 25; i++) await operation.getByRole('button', { name: 'Ponto de Ana Beatriz de Teste · equipe A', exact: true }).click()
  for (let i = 0; i < 23; i++) await operation.getByRole('button', { name: 'Ponto de Carla Maria de Teste · equipe B', exact: true }).click()
  await operation.getByRole('button', { name: 'Encerrar set', exact: true }).click()
  await operation.getByRole('button', { name: 'Confirmar encerramento do set', exact: true }).click()
  await preview.locator('[data-game-id="teste-volei-1"] .sb-set-history').waitFor()
  assert.match(await preview.locator('[data-game-id="teste-volei-1"] .sb-set-history').innerText(), /25 : 23/)
  record('Vôlei de teste: pontos, dois jogos e encerramento de set refletidos na prévia')
  await sports.getByRole('button', { name: 'Handebol', exact: true }).click()
  await operation.getByRole('button', { name: 'Gol de Ana Beatriz de Teste · equipe A', exact: true }).click()
  const periods = operation.getByRole('region', { name: 'Períodos da partida', exact: true })
  await periods.getByRole('button', { name: 'Encerrar 1º tempo', exact: true }).click()
  await periods.getByRole('button', { name: 'Confirmar intervalo', exact: true }).click()
  await preview.getByText('Intervalo · 1º tempo', { exact: true }).waitFor()
  await periods.getByRole('button', { name: 'Preparar 2º tempo', exact: true }).click()
  await periods.getByRole('button', { name: 'Iniciar 2º tempo', exact: true }).click()
  await preview.getByText('2º tempo', { exact: true }).waitFor()
  record('Handebol de teste: gol, intervalo e segundo tempo nos controles e na TV')
  await page.setViewportSize({ width: 390, height: 844 })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  await page.screenshot({ path: `${output}/local-test-mobile.png`, fullPage: true })
  await testMode.getByRole('button', { name: 'Reiniciar todos os testes', exact: true }).click()
  assert.equal(await preview.locator('.sb-score').first().innerText(), '0')
  await testMode.getByRole('button', { name: 'Sair do modo teste', exact: true }).click()
  await page.getByRole('button', { name: 'Iniciar modo de teste', exact: true }).waitFor()
  assert.deepEqual(await readGames(), before)
  assert.deepEqual(await localRequest(`${base}/broadcastSettings/scoreboard`), selectionBefore)
  assert.equal(await officialTV.locator('.sb-match').count(), 0)
  assert.deepEqual(writes, [])
  assert.deepEqual(errors, [])
  record('Sem gravações: banco e seleção oficial preservados; teste reinicia e se adapta ao celular')
  writeFileSync(`${output}/local-test-result.json`, JSON.stringify({ passed: true, results, writes, errors, project: PROJECT }, null, 2))
} catch (error) {
  await page?.screenshot({ path: `${output}/local-test-failure.png`, fullPage: true }).catch(() => {})
  writeFileSync(`${output}/local-test-result.json`, JSON.stringify({ passed: false, results, writes, errors, error: error.stack }, null, 2))
  console.error(error.stack); process.exitCode = 1
} finally { await browser?.close() }
